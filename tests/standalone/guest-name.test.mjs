import { cleanGuestName, readGuestName, readGuestToken } from '../../resources/js/public/guest-name.js';
let fail = 0; const ok = (n, c) => { if (!c) { fail++; console.log('FAIL', n); } else console.log('  ok  ', n); };
ok('plain', readGuestName('?to=Budi%20Santoso') === 'Budi Santoso');
ok('plus is a space', readGuestName('?to=Budi+Santoso') === 'Budi Santoso');
ok('ampersand', readGuestName('?to=Ni%20Luh%20Ayu%20%26%20Keluarga') === 'Ni Luh Ayu & Keluarga');
ok('html stays text (no tags interpreted here: textContent later)', readGuestName('?to=%3Cimg%20src%3Dx%20onerror%3Dalert(1)%3E') === '<img src=x onerror=alert(1)>');
ok('control chars removed', readGuestName('?to=Bu%00di%0Ab') === 'Bu di b');
ok('bidi override removed', !/[\u202E]/.test(readGuestName('?to=Ahmad%E2%80%AEevil')));
ok('zero width removed', readGuestName('?to=A%E2%80%8BB') === 'A B');
ok('empty -> null', readGuestName('?to=') === null && readGuestName('') === null);
ok('whitespace only -> null', readGuestName('?to=%20%20%20') === null);
ok('truncated to 60 graphemes', Array.from(new Intl.Segmenter().segment(readGuestName('?to=' + 'a'.repeat(100)))).length === 60);
ok('emoji family not split', cleanGuestName('👨‍👩‍👧‍👦'.repeat(70), 60) !== null && Array.from(new Intl.Segmenter().segment(cleanGuestName('👨‍👩‍👧‍👦'.repeat(70), 60))).length === 60);
ok('unicode kept', readGuestName('?to=Zo%C3%AB%20%E6%97%A5%E6%9C%AC') === 'Zoë 日本');
ok('non-string', cleanGuestName(null) === null);
ok('token valid', readGuestToken('?g=abc123def456') === 'abc123def456');
ok('token invalid length', readGuestToken('?g=abc') === null);
ok('token invalid chars', readGuestToken('?g=ABC123DEF45!') === null);
ok('token missing', readGuestToken('?to=x') === null);
ok('Persian ZWNJ kept', readGuestName('?to=' + encodeURIComponent('می\u200cخواهم')) === 'می\u200cخواهم');
process.exit(fail ? 1 : 0);
